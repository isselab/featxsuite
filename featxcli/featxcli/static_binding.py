"""Compile-time binding of the static early features.

A static early feature is compiled into the manual composition that hosts it,
behind a macro this module writes. A feature whose macro is absent is not in
the binary at all, so it cannot be activated at runtime: selecting it takes a
rebuild and a redeploy. That is the point of binding early and statically, and
it is what keeps a deployment down to the features its configuration asked
for.

The header is generated rather than kept by hand, so that a selection made in
the configuration and the binary that gets built cannot disagree.
"""

import glob
import os
import re

#: The header each manual composition includes to learn what was selected.
HEADER = os.path.join("include", "featxbinder", "static_features.h")

#: The package the header belongs to, and which every manual composition
#: depends on to find it.
OWNER = "featxbinder"

PREAMBLE = """\
// Generated by `ros2 featx start_config` from the feature configuration.
// Edits here are overwritten: change the configuration instead.
//
// Each macro is one feature bound static and early, compiled into the manual
// composition that hosts it. A feature that is absent from this file is absent
// from the binary and cannot be activated at runtime; selecting it takes a
// rebuild and a redeploy.

#ifndef FEATXBINDER_STATIC_FEATURES_H
#define FEATXBINDER_STATIC_FEATURES_H

"""

EPILOGUE = """
#endif  // FEATXBINDER_STATIC_FEATURES_H
"""


def is_static_early(config):
    """Whether a configuration entry is bound statically and early.

    A parameter carries no binding of its own, so it is never one of these:
    it is bound with the node it belongs to.
    """
    return config.get("bindingMode") == "Static" and config.get("bindingTime") == "Early"


def selected(configs):
    """The static early features the configuration selects, in model order."""
    return [c["name"] for c in configs["configs"] if is_static_early(c) and c["isSelected"]]


def deselected(configs):
    """The static early features the configuration leaves out.

    Worth knowing separately: a deselected feature that is still installed from
    an earlier build is still deployed, whatever this header now says.
    """
    return [c["name"] for c in configs["configs"] if is_static_early(c) and not c["isSelected"]]


def macro(feature_name):
    """The macro a feature is compiled behind."""
    return re.sub(r"[^A-Za-z0-9]", "_", feature_name).upper()


def header(features):
    """Render the header for a set of selected features."""
    defines = "".join(f"#define {macro(name)} 1\n" for name in features)
    return PREAMBLE + defines + EPILOGUE


def locate(workspace):
    """Find the header in a workspace, or None.

    It is a source file, so it cannot be found through the ament index: that
    describes what is installed, and the compiler reads this before anything is.
    """
    for pattern in (
        os.path.join(workspace, "src", "*", OWNER, HEADER),
        os.path.join(workspace, "src", OWNER, HEADER),
        os.path.join(workspace, "*", OWNER, HEADER),
        os.path.join(workspace, OWNER, HEADER),
    ):
        found = sorted(glob.glob(pattern))
        if found:
            return found[0]

    return None


def find_workspace(start=None):
    """Walk up from a directory to the workspace that encloses it.

    A workspace is identified by having a src/ that holds featxbinder: that is
    both where colcon expects to be run from and where the header can be
    found. Having the directory containing featxbinder be enough would be
    wrong, because running colcon there would build a second workspace inside
    the first.

    Walking up means the command works from anywhere inside a checkout rather
    than only from the root.
    """
    current = os.path.abspath(start or os.getcwd())

    while True:
        if os.path.isdir(os.path.join(current, "src")) and locate(current) is not None:
            return current

        parent = os.path.dirname(current)
        if parent == current:
            return None

        current = parent


def write(path, text):
    """Write the header, reporting whether it changed.

    An unchanged header is left alone so that the file's timestamp does not
    move and provoke a rebuild of everything that includes it.
    """
    try:
        with open(path) as existing:
            if existing.read() == text:
                return False
    except FileNotFoundError:
        pass

    with open(path, "w") as out:
        out.write(text)

    return True


def still_installed(workspace, features):
    """Which of these features still have an installed executable.

    colcon never removes what it has installed, so a feature dropped from the
    configuration keeps its binary until the install space is cleared. Such a
    feature is still deployed and could still be started, which is exactly what
    binding it statically was meant to prevent.
    """
    out = []
    for name in features:
        if os.path.isfile(os.path.join(workspace, "install", name, "lib", name, name)):
            out.append(name)
    return out
