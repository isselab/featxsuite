import os

import pytest

from featxcli import static_binding as sb


def configs(*entries):
    """Build a configuration document from (name, mode, time, selected) tuples."""
    return {
        "configs": [
            {"name": n, "bindingMode": m, "bindingTime": t, "isSelected": s}
            for n, m, t, s in entries
        ]
    }


SAMPLE = configs(
    ("navigation", "Static", "Early", True),
    ("elevator", "Static", "Early", True),
    ("footprint", "Static", "Early", False),
    ("to_loading", "Dynamic", "Late", True),
    ("boot", "Static", "Late", True),
    ("probe", "Dynamic", "Early", True),
)


class TestWhatCountsAsStaticEarly:

    def test_only_static_and_early_qualifies(self):
        assert sb.is_static_early({"bindingMode": "Static", "bindingTime": "Early"})

    @pytest.mark.parametrize("mode,time", [
        ("Static", "Late"),
        ("Dynamic", "Early"),
        ("Dynamic", "Late"),
    ])
    def test_every_other_binding_does_not(self, mode, time):
        assert not sb.is_static_early({"bindingMode": mode, "bindingTime": time})

    def test_a_parameter_has_no_binding_and_so_never_qualifies(self):
        # A parameter is bound with the node it belongs to, so its entry
        # carries no bindingMode or bindingTime at all.
        assert not sb.is_static_early({"name": "vel_max", "isSelected": True})


class TestSelection:

    def test_selected_takes_only_chosen_static_early_features(self):
        assert sb.selected(SAMPLE) == ["navigation", "elevator"]

    def test_deselected_takes_the_static_early_features_left_out(self):
        assert sb.deselected(SAMPLE) == ["footprint"]

    def test_loadable_features_appear_in_neither(self):
        both = sb.selected(SAMPLE) + sb.deselected(SAMPLE)
        for loadable in ("to_loading", "boot", "probe"):
            assert loadable not in both

    def test_order_follows_the_model(self):
        # The header should read like the model, not like an alphabetical list.
        assert sb.selected(configs(
            ("shelf", "Static", "Early", True),
            ("elevator", "Static", "Early", True),
        )) == ["shelf", "elevator"]


class TestMacroNames:

    @pytest.mark.parametrize("feature,expected", [
        ("navigation", "NAVIGATION"),
        ("to_loading", "TO_LOADING"),
        ("init-checks", "INIT_CHECKS"),
        ("RB 1 base", "RB_1_BASE"),
    ])
    def test_a_macro_is_the_name_upcased_with_separators_normalised(self, feature, expected):
        assert sb.macro(feature) == expected


class TestHeader:

    def test_it_defines_every_selected_feature(self):
        text = sb.header(["navigation", "elevator"])
        assert "#define NAVIGATION 1" in text
        assert "#define ELEVATOR 1" in text

    def test_it_defines_nothing_else(self):
        text = sb.header(["navigation"])
        assert "FOOTPRINT" not in text
        assert text.count("#define ") == 2  # the feature, plus the include guard

    def test_it_is_guarded_against_double_inclusion(self):
        text = sb.header(["navigation"])
        assert "#ifndef FEATXBINDER_STATIC_FEATURES_H" in text
        assert text.rstrip().endswith("#endif  // FEATXBINDER_STATIC_FEATURES_H")

    def test_it_says_it_is_generated(self):
        assert "Generated by" in sb.header([])

    def test_an_empty_selection_is_still_a_valid_header(self):
        text = sb.header([])
        assert "#ifndef" in text and "#endif" in text
        assert "#define FEATXBINDER_STATIC_FEATURES_H" in text


class TestWrite:

    def test_it_creates_the_header(self, tmp_path):
        target = tmp_path / "static_features.h"

        assert sb.write(str(target), "#define NAVIGATION 1\n") is True
        assert target.read_text() == "#define NAVIGATION 1\n"

    def test_rewriting_the_same_text_reports_no_change(self, tmp_path):
        target = tmp_path / "static_features.h"
        sb.write(str(target), "same\n")

        # An unchanged header must be left alone, or its timestamp moves and
        # everything that includes it rebuilds for nothing.
        before = target.stat().st_mtime_ns
        assert sb.write(str(target), "same\n") is False
        assert target.stat().st_mtime_ns == before

    def test_different_text_is_written_and_reported(self, tmp_path):
        target = tmp_path / "static_features.h"
        sb.write(str(target), "old\n")

        assert sb.write(str(target), "new\n") is True
        assert target.read_text() == "new\n"


class TestLocate:

    def place(self, root, *parts):
        path = root.joinpath(*parts, "featxbinder", "include", "featxbinder")
        path.mkdir(parents=True)
        header = path / "static_features.h"
        header.write_text("")
        return header

    def test_it_finds_the_header_in_a_nested_source_layout(self, tmp_path):
        header = self.place(tmp_path, "src", "featx_suite")
        assert sb.locate(str(tmp_path)) == str(header)

    def test_it_finds_the_header_directly_under_src(self, tmp_path):
        header = self.place(tmp_path, "src")
        assert sb.locate(str(tmp_path)) == str(header)

    def test_it_finds_the_header_beside_the_workspace(self, tmp_path):
        header = self.place(tmp_path)
        assert sb.locate(str(tmp_path)) == str(header)

    def test_a_workspace_without_featxbinder_gives_nothing(self, tmp_path):
        (tmp_path / "src").mkdir()
        assert sb.locate(str(tmp_path)) is None


class TestStillInstalled:

    def install(self, root, name):
        exe = root / "install" / name / "lib" / name / name
        exe.parent.mkdir(parents=True)
        exe.write_text("")

    def test_it_names_a_dropped_feature_that_is_still_deployed(self, tmp_path):
        self.install(tmp_path, "shelf")

        # colcon never uninstalls, so a deselected feature keeps its binary.
        assert sb.still_installed(str(tmp_path), ["shelf", "footprint"]) == ["shelf"]

    def test_nothing_installed_means_nothing_to_report(self, tmp_path):
        assert sb.still_installed(str(tmp_path), ["shelf"]) == []

    def test_a_directory_without_the_executable_does_not_count(self, tmp_path):
        (tmp_path / "install" / "shelf" / "lib" / "shelf").mkdir(parents=True)
        assert sb.still_installed(str(tmp_path), ["shelf"]) == []


class TestAgainstTheRealModel:

    def test_the_generated_header_matches_what_was_kept_by_hand(self):
        """The hand-maintained header is what the generator must reproduce.

        If this ever fails, either the configuration changed or the generator
        drifted; both are worth noticing.
        """
        from featxcli.configurator import Configurator

        configurator = Configurator()
        cfg = configurator.readConfigs()
        text = sb.header(sb.selected(cfg))

        for feature in sb.selected(cfg):
            assert f"#define {sb.macro(feature)} 1" in text

        header = sb.locate(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
        if header is None:
            pytest.skip("featxbinder source not present")

        with open(header) as existing:
            for feature in sb.selected(cfg):
                existing.seek(0)
                assert sb.macro(feature) in existing.read()
